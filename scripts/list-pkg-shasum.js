/**
 * List and verify npm publish shasums for packages that need to be released.
 *
 * Usage:
 *   node scripts/list-pkg-shasum.js
 *   node scripts/list-pkg-shasum.js --out shasums.json
 *   node scripts/list-pkg-shasum.js --verify shasums.json
 *   node scripts/list-pkg-shasum.js --publish shasums.json
 *   node scripts/list-pkg-shasum.js --compare shasums.json
 *   node scripts/list-pkg-shasum.js --verify shasums.json --local-publish-registry http://127.0.0.1:4873
 *   node scripts/list-pkg-shasum.js --publish shasums.json --tag beta
 *   node scripts/list-pkg-shasum.js --compare shasums.json --allow-manifest-registry-mismatch
 *
 * --allow-manifest-registry-mismatch only overrides registry mismatch, and only in
 * compare mode. Tag mismatch is never overridable; publish/verify never override
 * registry mismatch.
 *
 * By default, only local name@version pairs that are missing from the npm
 * registry are included. Existing published versions are skipped because their
 * historical tarballs cannot be regenerated by a new local pack operation.
 *
 * The shasum is computed from a temporary copy of each package. In that copy,
 * workspace: dependency ranges are replaced with regular semver ranges before
 * running npm publish. The real package.json files are not changed.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const args = process.argv.slice(2);
const ALL_MODE = args.includes('--all');
const OUT_FILE = readArgValue('--out');
const VERIFY_FILE = readArgValue('--verify');
const PUBLISH_FILE = readArgValue('--publish');
const COMPARE_FILE = readArgValue('--compare');
const TAG = readArgValue('--tag') || 'latest';
const REGISTRY = readArgValue('--registry');
const LOCAL_PUBLISH_REGISTRY = readArgValue('--local-publish-registry');
const DRY_RUN_ATTEMPTS = Number(readArgValue('--attempts') || 2);
const REGISTRY_TIMEOUT_MS = Number(readArgValue('--registry-timeout-ms') || 30000);
const REGISTRY_CONCURRENCY = Number(readArgValue('--registry-concurrency') || 8);
const ALLOW_MANIFEST_MISMATCH = args.includes('--allow-manifest-registry-mismatch');

if (!Number.isInteger(DRY_RUN_ATTEMPTS) || DRY_RUN_ATTEMPTS < 1) {
    console.error('--attempts must be a positive integer');
    process.exit(1);
}

if (!Number.isInteger(REGISTRY_TIMEOUT_MS) || REGISTRY_TIMEOUT_MS < 1000) {
    console.error('--registry-timeout-ms must be an integer >= 1000');
    process.exit(1);
}

if (!Number.isInteger(REGISTRY_CONCURRENCY) || REGISTRY_CONCURRENCY < 1) {
    console.error('--registry-concurrency must be a positive integer');
    process.exit(1);
}

// --publish/--verify/--compare select mutually exclusive modes. main() checks them
// in that order and returns on the first match, so a stray second flag would be
// silently ignored. The dangerous case is `--publish x --verify y --local-publish-registry z`:
// the --local-publish-registry guard below is satisfied by --verify, but main() runs
// publishManifest() (which ignores LOCAL_PUBLISH_REGISTRY and uses the real REGISTRY),
// publishing for real when a local-registry dry run was intended. Reject up front.
const selectedModes = [PUBLISH_FILE && '--publish', VERIFY_FILE && '--verify', COMPARE_FILE && '--compare'].filter(
    Boolean
);
if (selectedModes.length > 1) {
    console.error(`Only one of --publish/--verify/--compare may be used at a time (got: ${selectedModes.join(', ')}).`);
    process.exit(1);
}

if (LOCAL_PUBLISH_REGISTRY && !VERIFY_FILE) {
    console.error('--local-publish-registry must be used together with --verify <manifest>');
    process.exit(1);
}

function readArgValue(name) {
    const index = args.indexOf(name);
    if (index === -1) return null;
    const value = args[index + 1];
    if (!value || value.startsWith('--')) {
        console.error(`Missing value for ${name}`);
        process.exit(1);
    }
    return value;
}

const DIRS = [
    path.resolve(__dirname, '../packages/adapters'),
    path.resolve(__dirname, '../packages/adapters/evm'),
    path.resolve(__dirname, '../packages/react'),
    path.resolve(__dirname, '../packages/vue'),
];

// Step 1: collect all non-private top-level packages.

const packages = [];
const workspacePackages = [];

DIRS.forEach((dir) => {
    if (!fs.existsSync(dir)) return;
    fs.readdirSync(dir)
        .filter((entry) => !entry.startsWith('.') && entry !== 'evm')
        .forEach((entry) => {
            const pkgDir = path.resolve(dir, entry);
            const pkgPath = path.resolve(pkgDir, 'package.json');
            if (!fs.existsSync(pkgPath)) return;
            let pkg;
            try {
                pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
            } catch (e) {
                console.error(`Malformed package.json at ${pkgPath}: ${e.message}`);
                process.exit(1);
            }
            if (typeof pkg.name !== 'string' || typeof pkg.version !== 'string') {
                console.error(`Invalid package.json at ${pkgPath}: "name" and "version" must be strings.`);
                process.exit(1);
            }
            workspacePackages.push({
                name: pkg.name,
                version: pkg.version,
                dir: pkgDir,
                private: Boolean(pkg.private),
            });
            if (pkg.private) return;
            packages.push({ name: pkg.name, version: pkg.version, dir: pkgDir });
        });
});

const versionByName = new Map(workspacePackages.map(({ name, version }) => [name, version]));
const packageById = new Map(packages.map((pkg) => [`${pkg.name}@${pkg.version}`, pkg]));

// Registry helpers.

function getErrorMessage(error) {
    return `${error.stderr ? error.stderr.toString() : ''}\n${error.message || error.toString()}`;
}

function npmCacheEnv() {
    return {
        ...process.env,
        npm_config_cache: process.env.npm_config_cache || path.join(os.tmpdir(), 'npm-cache'),
    };
}

function isNpmNotFound(error) {
    return getErrorMessage(error).includes('E404');
}

function isNpmPublishConflict(error) {
    const message = getErrorMessage(error);
    return (
        message.includes('EPUBLISHCONFLICT') ||
        message.includes('cannot publish over the previously published versions')
    );
}

function npmConfigGet(key) {
    try {
        const value = execFileSync('npm', ['config', 'get', key], {
            stdio: ['ignore', 'pipe', 'ignore'],
        })
            .toString()
            .trim();
        return value && value !== 'undefined' && value !== 'null' ? value : null;
    } catch {
        return null;
    }
}

const registryResolutionCache = new Map();

// Resolve the registry the same way `npm publish` does so shasum queries hit the
// SAME registry we published to. Without --registry, `npm publish` uses the
// scope-specific registry (@scope:registry) when set, else the global registry,
// else npmjs. Hardcoding npmjs here would publish to A but verify against B when
// the local npm config points at a private/scope registry.
function resolveDefaultRegistry(name) {
    const scope = name && name.startsWith('@') ? name.split('/')[0] : null;
    const cacheKey = scope || '(default)';
    if (registryResolutionCache.has(cacheKey)) return registryResolutionCache.get(cacheKey);
    const resolved =
        (scope && npmConfigGet(`${scope}:registry`)) || npmConfigGet('registry') || 'https://registry.npmjs.org/';
    registryResolutionCache.set(cacheKey, resolved);
    return resolved;
}

function getRegistryBase(registry = REGISTRY) {
    return (registry || 'https://registry.npmjs.org/').replace(/\/+$/, '');
}

function getPackageVersionUrl(name, version, registry = REGISTRY) {
    // Fall back to npm's resolved registry (scope-aware) rather than hardcoded npmjs.
    const base = getRegistryBase(registry || resolveDefaultRegistry(name));
    return `${base}/${encodeURIComponent(name).replace('%2F', '%2f')}/${encodeURIComponent(version)}`;
}

async function fetchRegistryPackageVersion(name, version, registry = REGISTRY) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), REGISTRY_TIMEOUT_MS);

    try {
        const response = await fetch(getPackageVersionUrl(name, version, registry), {
            headers: { accept: 'application/vnd.npm.install-v1+json, application/json' },
            signal: controller.signal,
        });

        if (response.status === 404) return null;
        if (!response.ok) {
            throw new Error(`HTTP ${response.status} ${response.statusText}`);
        }

        return await response.json();
    } finally {
        clearTimeout(timeout);
    }
}

async function getRegistryVersion(name, version, registry = REGISTRY) {
    const metadata = await fetchRegistryPackageVersion(name, version, registry);
    return metadata ? metadata.version || null : null;
}

async function getRegistryShasum(name, version, registry = REGISTRY) {
    const metadata = await fetchRegistryPackageVersion(name, version, registry);
    return metadata && metadata.dist ? metadata.dist.shasum || null : null;
}

async function mapWithConcurrency(items, concurrency, mapper) {
    const results = new Array(items.length);
    let nextIndex = 0;

    const workers = Array.from({ length: Math.min(concurrency, items.length) }, async () => {
        while (nextIndex < items.length) {
            const index = nextIndex;
            nextIndex += 1;
            results[index] = await mapper(items[index], index);
        }
    });

    await Promise.all(workers);
    return results;
}

// Manifest and table helpers.

function readManifest(file) {
    const content = fs.readFileSync(path.resolve(file), 'utf8');
    const manifest = JSON.parse(content);
    const entries = Array.isArray(manifest) ? manifest : manifest.packages;
    if (!Array.isArray(entries)) {
        throw new Error('Manifest must be an array or an object with a packages array.');
    }
    // Keep the environment metadata captured at generation time so verify/publish/compare
    // can refuse to run against a different tag/registry than the manifest was built for.
    // For the legacy array form there is no metadata to carry.
    const meta = Array.isArray(manifest)
        ? {}
        : {
              tag: manifest.tag,
              registry: manifest.registry,
              packageManager: manifest.packageManager,
              workspaceDependencyMode: manifest.workspaceDependencyMode,
          };
    // Validate each entry's shape so a malformed manifest cannot push
    // `undefined@undefined` or a non-hex shasum into verify/publish/compare.
    const SHASUM_RE = /^[0-9a-f]{40}$/;
    const normalizedEntries = entries.map((entry, index) => {
        const { name, version, shasum } = entry || {};
        if (typeof name !== 'string' || typeof version !== 'string' || typeof shasum !== 'string') {
            console.error(`Manifest entry #${index} is missing string name/version/shasum: ` + JSON.stringify(entry));
            process.exit(1);
        }
        if (!SHASUM_RE.test(shasum)) {
            console.error(
                `Manifest entry #${index} (${name}@${version}) has an invalid shasum "${shasum}" (expected 40 lowercase hex chars).`
            );
            process.exit(1);
        }
        return { name, version, shasum };
    });
    return { meta, entries: normalizedEntries };
}

// Resolve the registry this run would actually publish to, mirroring how the
// manifest was generated (see resolveDefaultRegistry above). Used to check that
// the current environment matches the manifest's declared registry.
function currentPublishRegistry() {
    return REGISTRY || resolveDefaultRegistry(undefined) || 'https://registry.npmjs.org/';
}

// Fail closed when the manifest's declared tag/registry does not match the current
// run. Prevents a manifest generated for `--tag beta` / a private registry from being
// published under the default `latest` tag / a different registry just because the
// shasum happens to match.
//
// Tag mismatch is never overridable - a beta manifest published under `latest` is
// always a release incident. Registry mismatch is overridable ONLY in compare mode,
// where the operation is a read-only diff between two registries; publish/verify must
// never bypass it. The flag is named --allow-manifest-registry-mismatch (registry only,
// not tag) and the implementation matches that name.
function assertManifestEnvironment(meta, mode) {
    if (!meta) return;

    if (meta.tag && meta.tag !== TAG) {
        console.error(
            `Manifest tag "${meta.tag}" does not match current --tag "${TAG}" (${mode} mode). ` +
                `Re-run with --tag ${meta.tag}. Tag mismatch cannot be overridden.`
        );
        process.exit(1);
    }

    // Registry check. Two failure modes:
    //   1. manifest recorded a concrete registry (generator passed --registry) and the
    //      current resolved registry differs;
    //   2. manifest recorded "default npm registry" (generator used the default) but the
    //      current run explicitly passed --registry, i.e. the two runs are not using the
    //      same resolution path. This catches "generate with default, publish with
    //      --registry B" which would otherwise slip past because "default npm registry"
    //      is a literal, not a resolvable URL.
    // Note: this is an environment-level check and resolves the *global* default registry
    // (npm config `registry`). It cannot mirror npm's per-scope `@scope:registry` for
    // every package in one pass; the per-package publish call still goes through npm's
    // own scope-aware resolution. The check below catches the documented attack surface
    // (explicit --registry drift between generate and publish).
    if (meta.registry) {
        const current = currentPublishRegistry();
        const manifestIsDefaultLiteral = meta.registry === 'default npm registry';
        const currentIsExplicit = Boolean(REGISTRY);
        const mismatched = manifestIsDefaultLiteral
            ? currentIsExplicit // default-on-generate vs explicit-on-publish
            : meta.registry !== current;
        if (mismatched) {
            const canOverride = ALLOW_MANIFEST_MISMATCH && mode === 'compare';
            if (canOverride) {
                console.warn(
                    `Manifest registry "${meta.registry}" does not match resolved registry "${current}" (compare mode). ` +
                        `Continuing because --allow-manifest-registry-mismatch was provided.`
                );
                return;
            }
            console.error(
                `Manifest registry "${meta.registry}" does not match resolved registry "${current}" (${mode} mode). ` +
                    `Re-run without --registry (to use the default), or against ${meta.registry}, or (compare mode only) pass --allow-manifest-registry-mismatch.`
            );
            process.exit(1);
        }
    }
}

function printTable(headers, rows) {
    const widths = headers.map((header, index) =>
        Math.max(header.length, ...rows.map((row) => String(row[index] ?? '').length))
    );
    const sep = `+-${widths.map((width) => '-'.repeat(width)).join('-+-')}-+`;
    console.log('\n' + sep);
    console.log(`| ${headers.map((header, index) => header.padEnd(widths[index])).join(' | ')} |`);
    console.log(sep);
    rows.forEach((row) => {
        console.log(`| ${row.map((cell, index) => String(cell ?? '').padEnd(widths[index])).join(' | ')} |`);
    });
    console.log(sep);
}

// Temporary publish directory helpers.

function copyPackageToTemp(dir) {
    const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'tronwallet-publish-'));
    const tempDir = path.join(tempRoot, 'package');

    fs.cpSync(dir, tempDir, {
        recursive: true,
        filter: (source) => {
            const name = path.basename(source);
            return name !== 'node_modules' && name !== '.turbo' && name !== 'coverage' && !name.endsWith('.tgz');
        },
    });

    return { tempRoot, tempDir };
}

function freezeWorkspaceSpec(depName, spec) {
    if (typeof spec !== 'string' || !spec.startsWith('workspace:')) return spec;

    const workspaceVersion = versionByName.get(depName);
    if (!workspaceVersion) {
        throw new Error(`Cannot resolve workspace dependency ${depName}`);
    }

    const range = spec.slice('workspace:'.length);
    if (!range || range === '*') return workspaceVersion;
    if (range === '^' || range === '~') return `${range}${workspaceVersion}`;
    return range;
}

function freezeWorkspaceDependencies(tempDir) {
    const pkgPath = path.join(tempDir, 'package.json');
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    const sections = ['dependencies', 'devDependencies', 'peerDependencies', 'optionalDependencies'];
    const changed = [];

    sections.forEach((section) => {
        const deps = pkg[section];
        if (!deps) return;

        Object.keys(deps).forEach((depName) => {
            const before = deps[depName];
            const after = freezeWorkspaceSpec(depName, before);
            if (after !== before) {
                deps[depName] = after;
                changed.push({ section, name: depName, before, after });
            }
        });
    });

    if (changed.length > 0) {
        fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 4) + '\n');
    }

    return changed;
}

function withPreparedPackage(pkg, callback) {
    const { tempRoot, tempDir } = copyPackageToTemp(pkg.dir);
    try {
        const frozenDependencies = freezeWorkspaceDependencies(tempDir);
        return callback(tempDir, frozenDependencies);
    } finally {
        fs.rmSync(tempRoot, { recursive: true, force: true });
    }
}

// npm publish helpers.

function findLastJsonObject(text) {
    let last = null;

    for (let start = 0; start < text.length; start++) {
        if (text[start] !== '{') continue;

        let depth = 0;
        let inString = false;
        let escape = false;

        for (let end = start; end < text.length; end++) {
            const char = text[end];

            if (inString) {
                if (escape) {
                    escape = false;
                } else if (char === '\\') {
                    escape = true;
                } else if (char === '"') {
                    inString = false;
                }
                continue;
            }

            if (char === '"') {
                inString = true;
            } else if (char === '{') {
                depth += 1;
            } else if (char === '}') {
                depth -= 1;
                if (depth === 0) {
                    try {
                        last = JSON.parse(text.slice(start, end + 1));
                    } catch {
                        // Ignore non-JSON braces from lifecycle output.
                    }
                    start = end;
                    break;
                }
            }
        }
    }

    return last;
}

function normalizePublishJson(json, dir) {
    if (!json || !json.name || !json.version || !json.shasum) {
        throw new Error(`Unable to parse npm publish JSON for ${dir}`);
    }
    return {
        name: json.name,
        version: json.version,
        shasum: json.shasum,
        integrity: json.integrity,
        filename: json.filename,
        size: json.size,
        unpackedSize: json.unpackedSize,
        entryCount: json.entryCount,
    };
}

function runNpmPublish(tempDir, { dryRun = false, registry = null } = {}) {
    const npmArgs = ['publish', '--json', '--tag', TAG, '--access', 'public'];
    if (dryRun) npmArgs.push('--dry-run');
    if (registry) npmArgs.push('--registry', registry);

    const out = execFileSync('npm', npmArgs, {
        cwd: tempDir,
        stdio: ['ignore', 'pipe', 'pipe'],
        env: npmCacheEnv(),
        maxBuffer: 64 * 1024 * 1024,
    }).toString();

    return normalizePublishJson(findLastJsonObject(out), tempDir);
}

function getSinglePublishDryRunInfo(pkg) {
    return withPreparedPackage(pkg, (tempDir, frozenDependencies) => ({
        ...runNpmPublish(tempDir, { dryRun: true }),
        frozenDependencyCount: frozenDependencies.length,
    }));
}

function getPublishDryRunInfo(pkg) {
    const results = [];

    for (let index = 0; index < DRY_RUN_ATTEMPTS; index++) {
        results.push(getSinglePublishDryRunInfo(pkg));
    }

    const [first] = results;
    const unstable = results.find((result) => result.shasum !== first.shasum);
    if (unstable) {
        throw new Error(`unstable dry-run shasum: ${results.map((result) => result.shasum).join(', ')}`);
    }

    return first;
}

function publishPackage(pkg, registry) {
    return withPreparedPackage(pkg, (tempDir, frozenDependencies) => {
        try {
            return {
                ...runNpmPublish(tempDir, { registry }),
                alreadyPublished: false,
                frozenDependencyCount: frozenDependencies.length,
            };
        } catch (e) {
            if (!isNpmPublishConflict(e)) throw e;
            return {
                name: pkg.name,
                version: pkg.version,
                shasum: null,
                alreadyPublished: true,
                frozenDependencyCount: frozenDependencies.length,
            };
        }
    });
}

function publishToLocalRegistry(pkg, registry) {
    return publishPackage(pkg, registry);
}

// Compare a previously generated manifest with a registry.

async function compareManifestWithRegistry(file, registry = REGISTRY) {
    const { meta, entries: expected } = readManifest(file);
    assertManifestEnvironment(meta, 'compare');
    const rows = await mapWithConcurrency(expected, REGISTRY_CONCURRENCY, async ({ name, version, shasum }) => {
        process.stdout.write(`Checking ${name}@${version}... `);
        try {
            const registryShasum = await getRegistryShasum(name, version, registry);
            const status = registryShasum === shasum ? 'OK' : 'MISMATCH';
            console.log(status);
            return [name, version, shasum, registryShasum || '(missing)', status];
        } catch (e) {
            console.log('failed');
            console.error(`Unable to query npm registry for ${name}@${version}: ${e.message || e}`);
            process.exit(1);
        }
    });

    printTable(['Package', 'Version', 'Expected shasum', 'Registry shasum', 'Status'], rows);
    return rows.some((row) => row[4] !== 'OK') ? 1 : 0;
}

// Verify against local dry-run, or publish to a local registry and compare.

async function verifyManifest(file) {
    const { meta, entries: expected } = readManifest(file);
    assertManifestEnvironment(meta, 'verify');
    const rows = [];

    for (const { name, version, shasum } of expected) {
        const id = `${name}@${version}`;
        const pkg = packageById.get(id);
        process.stdout.write(`${LOCAL_PUBLISH_REGISTRY ? 'Publishing' : 'Verifying'} ${id}... `);
        if (!pkg) {
            console.log('missing locally');
            rows.push([name, version, shasum, '(missing)', '(missing)', '(missing)', 'MISMATCH']);
            continue;
        }

        let dryRun;
        try {
            dryRun = getPublishDryRunInfo(pkg).shasum;
        } catch (e) {
            console.log('failed');
            console.error(`Unable to run npm publish dry-run for ${id}: ${e.message || e}`);
            process.exit(1);
        }

        if (!LOCAL_PUBLISH_REGISTRY) {
            const status = dryRun === shasum ? 'OK' : 'MISMATCH';
            console.log(status);
            rows.push([name, version, shasum, dryRun, status]);
            continue;
        }

        let publishShasum = null;
        let registryShasum = null;
        try {
            const publishInfo = publishToLocalRegistry(pkg, LOCAL_PUBLISH_REGISTRY);
            publishShasum = publishInfo.shasum;
            registryShasum = await getRegistryShasum(name, version, LOCAL_PUBLISH_REGISTRY);
        } catch (e) {
            console.log('failed');
            console.error(`Unable to publish/query local registry for ${id}: ${e.message || e}`);
            process.exit(1);
        }

        const publishMatches = publishShasum === null || publishShasum === shasum;
        const status = dryRun === shasum && publishMatches && registryShasum === shasum ? 'OK' : 'MISMATCH';
        console.log(status);
        rows.push([
            name,
            version,
            shasum,
            dryRun,
            publishShasum || '(already published)',
            registryShasum || '(missing)',
            status,
        ]);
    }

    if (LOCAL_PUBLISH_REGISTRY) {
        printTable(
            [
                'Package',
                'Version',
                'Expected shasum',
                'Dry-run shasum',
                'Publish shasum',
                'Local registry shasum',
                'Status',
            ],
            rows
        );
        return rows.some((row) => row[6] !== 'OK') ? 1 : 0;
    }

    printTable(['Package', 'Version', 'Expected shasum', 'Local dry-run shasum', 'Status'], rows);
    return rows.some((row) => row[4] !== 'OK') ? 1 : 0;
}

// Publish every package in a manifest and verify the resulting registry shasums.

async function publishManifest(file, registry = REGISTRY) {
    const { meta, entries: expected } = readManifest(file);
    assertManifestEnvironment(meta, 'publish');
    const verifyRows = [];
    const publishQueue = [];

    console.log(`\nVerifying ${expected.length} package(s) before publish.\n`);

    for (const { name, version, shasum } of expected) {
        const id = `${name}@${version}`;
        const pkg = packageById.get(id);
        process.stdout.write(`Dry-run publishing ${id}... `);

        if (!pkg) {
            console.log('missing locally');
            verifyRows.push([name, version, shasum, '(missing)', 'MISMATCH']);
            continue;
        }

        try {
            const dryRun = getPublishDryRunInfo(pkg).shasum;
            const status = dryRun === shasum ? 'OK' : 'MISMATCH';
            console.log(status);
            verifyRows.push([name, version, shasum, dryRun, status]);
            if (status === 'OK') publishQueue.push({ pkg, name, version, shasum });
        } catch (e) {
            console.log('failed');
            console.error(`Unable to run npm publish dry-run for ${id}: ${e.message || e}`);
            verifyRows.push([name, version, shasum, '(error)', 'MISMATCH']);
        }
    }

    printTable(['Package', 'Version', 'Expected shasum', 'Dry-run shasum', 'Status'], verifyRows);

    if (verifyRows.some((row) => row[4] !== 'OK')) {
        console.error('\nPublish aborted because one or more dry-run shasums do not match the manifest.');
        return 1;
    }

    const publishRows = [];
    console.log(`\nPublishing ${publishQueue.length} package(s) with tag "${TAG}".\n`);

    for (const { pkg, name, version, shasum } of publishQueue) {
        const id = `${name}@${version}`;
        let publishInfo = null;
        let registryShasum = null;
        process.stdout.write(`Publishing ${id}... `);

        try {
            publishInfo = publishPackage(pkg, registry);
            registryShasum = await getRegistryShasum(name, version, registry);
        } catch (e) {
            console.log('failed');
            console.error(`Unable to publish/query registry for ${id}: ${e.message || e}`);
            publishRows.push([name, version, shasum, '(error)', registryShasum || '(missing)', 'MISMATCH']);
            continue;
        }

        const publishMatches = publishInfo.alreadyPublished || publishInfo.shasum === shasum;
        const registryMatches = registryShasum === shasum;
        const status = publishMatches && registryMatches ? 'OK' : 'MISMATCH';
        console.log(status);
        publishRows.push([
            name,
            version,
            shasum,
            publishInfo.alreadyPublished ? '(already published)' : publishInfo.shasum,
            registryShasum || '(missing)',
            status,
        ]);
    }

    printTable(['Package', 'Version', 'Expected shasum', 'Publish shasum', 'Registry shasum', 'Status'], publishRows);

    return publishRows.some((row) => row[5] !== 'OK') ? 1 : 0;
}

async function selectPackagesToPublish() {
    if (ALL_MODE) return packages;

    const selected = [];
    const checked = await mapWithConcurrency(packages, REGISTRY_CONCURRENCY, async (pkg) => {
        const { name, version } = pkg;
        try {
            const registryVersion = await getRegistryVersion(name, version);
            if (registryVersion === version) {
                return { pkg, status: 'published, skipping', include: false };
            }

            return { pkg, status: 'not published, including', include: true };
        } catch (e) {
            console.error(`Unable to query npm registry for ${name}@${version}: ${e.message || e}`);
            console.error(
                'Use --all only for diagnostics; release manifests should be generated with registry access.'
            );
            process.exit(1);
        }
    });

    checked.forEach((result) => {
        console.log(`Checking ${result.pkg.name}@${result.pkg.version}... ${result.status}`);
        if (result.include) selected.push(result.pkg);
    });

    return selected;
}

async function main() {
    if (PUBLISH_FILE) {
        return publishManifest(PUBLISH_FILE);
    }

    if (COMPARE_FILE && !LOCAL_PUBLISH_REGISTRY) {
        return compareManifestWithRegistry(COMPARE_FILE);
    }

    if (VERIFY_FILE) {
        return verifyManifest(VERIFY_FILE);
    }

    // Step 2: select packages that need publishing.

    const selected = await selectPackagesToPublish();

    // Step 3: compute shasum for selected packages via npm publish dry-run.

    console.log(`\n${ALL_MODE ? 'All non-private' : 'Packages to publish'} (${selected.length}):\n`);
    console.log(
        `Running npm publish dry-run from temporary package copies with tag "${TAG}" (${DRY_RUN_ATTEMPTS} attempt(s) per package).\n`
    );

    const rows = [];
    selected.forEach((pkg) => {
        process.stdout.write(`Dry-run publishing ${pkg.name}@${pkg.version}... `);
        try {
            const info = getPublishDryRunInfo(pkg);
            console.log('done');
            rows.push({ ...pkg, ...info });
        } catch (e) {
            console.log('failed');
            console.warn(`  ! failed to dry-run publish ${pkg.dir}: ${e.message || e}`);
            rows.push({ ...pkg, shasum: '(error)' });
        }
    });

    // Step 4: print result table.

    if (rows.length === 0) {
        console.log('No packages to publish.');
        return 0;
    }

    printTable(
        ['Package', 'Version', 'Shasum'],
        rows.map(({ name, version, shasum }) => [name, version, shasum])
    );

    if (rows.some((row) => row.shasum === '(error)')) {
        console.error('\nOne or more packages produced unstable or invalid dry-run shasums. Manifest was not written.');
        return 1;
    }

    if (OUT_FILE) {
        const manifestPath = path.resolve(OUT_FILE);
        const manifest = {
            generatedAt: new Date().toISOString(),
            packageManager: 'npm',
            publishCommand: `npm publish --json --tag ${TAG} --access public`,
            dryRunCommand: `npm publish --dry-run --json --tag ${TAG} --access public`,
            workspaceDependencyMode: 'temporary-copy workspace: -> semver',
            selection: ALL_MODE ? 'all non-private packages (diagnostic)' : 'local name@version missing from registry',
            registry: REGISTRY || 'default npm registry',
            tag: TAG,
            dryRunAttempts: DRY_RUN_ATTEMPTS,
            packages: rows.map(({ dir, ...row }) => row),
        };
        fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
        console.log(`\nWrote shasum manifest: ${manifestPath}`);
    }

    return 0;
}

main()
    .then((exitCode) => {
        process.exit(exitCode);
    })
    .catch((e) => {
        console.error(e.message || e);
        process.exit(1);
    });
